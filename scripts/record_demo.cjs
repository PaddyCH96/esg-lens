// Exercises the running app. CI records real sources and real model results.
const {chromium}=require('playwright');
const fs=require('node:fs');
const assert=require('node:assert/strict');
(async()=>{
 fs.mkdirSync('docs/demo',{recursive:true});
 const browser=await chromium.launch({headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1000},recordVideo:{dir:'docs/demo/raw',size:{width:1440,height:1000}}});
 const page=await context.newPage(); const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8000');
 await page.getByText('● Models ready',{exact:true}).waitFor({timeout:60000});
 await page.waitForTimeout(1800);
 await page.locator('#workspace').scrollIntoViewIfNeeded();
 await page.locator('#tickers').fill('AAPL, XOM');
 await page.getByRole('button',{name:'Analyse portfolio'}).click();
 await page.locator('#portfolio button').first().waitFor({timeout:240000});
 await page.locator('#detail').waitFor();
 assert.equal(await page.locator('#portfolio button').count(),2);
 assert.ok(await page.locator('.document').count()>0,'Expected real stored evidence');
 await page.waitForTimeout(2000);
 await page.locator('#metrics').scrollIntoViewIfNeeded();
 await page.screenshot({path:'docs/demo/dashboard.png',fullPage:true});
 await page.waitForTimeout(2500);
 await page.locator('#documents').scrollIntoViewIfNeeded();await page.waitForTimeout(2500);
 await page.locator('summary').click();await page.locator('#provenance').scrollIntoViewIfNeeded();await page.waitForTimeout(2500);
 await page.locator('summary').click();
 await page.locator('#portfolio button').filter({hasText:'XOM'}).click();
 await page.getByRole('heading',{name:/XOM ·/}).waitFor();await page.locator('#detail').waitFor();
 await page.locator('#metrics').scrollIntoViewIfNeeded();await page.waitForTimeout(2500);
 const download=page.waitForEvent('download');await page.locator('#export').click();const file=await download;assert.equal(file.suggestedFilename(),'XOM-esg-lens.json');
 // Input error, missing company, narrow viewport, and refresh recovery.
 await page.locator('#company').fill('ZZZZZZZZZZ');await page.locator('#lookup button').click();await page.getByText(/No score for ZZZZZZZZZZ/).waitFor();
 await page.locator('#company').fill('AAPL');await page.locator('#lookup button').click();await page.locator('#detail').waitFor();
 await page.setViewportSize({width:390,height:844});await page.locator('#metrics').scrollIntoViewIfNeeded();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Mobile horizontal overflow');
 await page.screenshot({path:'docs/demo/mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.locator('#tickers').fill('$$');await page.getByRole('button',{name:'Analyse portfolio'}).click();await page.getByText(/Use valid company tickers/).waitFor();
 await page.locator('#tickers').fill('AAPL, XOM');
 const queuedResponse=page.waitForResponse(r=>r.url().endsWith('/portfolio/analyze')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Analyse portfolio'}).click();
 const queued=await (await queuedResponse).json();
 await page.evaluate(url=>sessionStorage.setItem('esg-job',url),queued.links.status);
 await page.reload();await page.locator('#portfolio button').first().waitFor({timeout:240000});await page.locator('#detail').waitFor();
 await page.locator('#workspace').scrollIntoViewIfNeeded();await page.waitForTimeout(1500);
 assert.deepEqual(errors,[],'Browser JavaScript errors');
 const video=page.video();await context.close();await video.saveAs('docs/demo/prototype.webm');await browser.close();
 fs.writeFileSync('docs/demo/recording.json',JSON.stringify({recorded_at:new Date().toISOString(),mode:process.env.ESG_RECORDING_MODE||'live',checks:['portfolio submission','evidence','company switch','JSON export','missing company','invalid ticker','mobile layout','refresh recovery','no JS errors']},null,2));
 console.log('Browser checks passed; video saved to docs/demo/prototype.webm');
})().catch(e=>{console.error(e);process.exit(1)});
